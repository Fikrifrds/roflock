/**
 * SHA-256, in portable TypeScript.
 *
 * Graph IR is the one package that must run everywhere — the compiler, the
 * runtime bridge, and the browser Playground all compute the same semantic
 * hash, and a run's recorded identity would be meaningless if the answer
 * depended on where it was computed. Reaching `node:crypto` made `graph-ir`
 * unimportable in a browser, which is the only reason this exists.
 *
 * It must produce digests identical to `node:crypto` — a test asserts exactly
 * that against known vectors and against the Node implementation itself, because
 * a subtly different hash would silently invalidate every recorded invocation
 * identity rather than failing loudly.
 */

