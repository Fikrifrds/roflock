import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { ExitCode } from './exit-codes.js';
import type { CliIo } from './main.js';
import { emitRuntimeError, emitUsageError } from './runtime-output.js';

interface Options {
  directory: string;
  json: boolean;
}

interface InitResult {
  root: string;
  created: string[];
  unchanged: string[];
  conflicts: string[];
}

class UsageError extends Error {}

const FILES: Record<string, string> = {
  'roflock.toml': `schema = 1
default_workflow = "workflows/bugfix.roflock"
profile = "profiles/local.toml"
policy = "policies/default.toml"
`,
  'profiles/local.toml': `schema = 1
name = "local"

# Authentication remains owned by each agent CLI. Never put credentials here.
`,
  'policies/default.toml': `schema = 1
name = "default"

[execution]
require_explicit_human_approval = true
`,
  'workflows/bugfix.roflock': `# Generated by roflock init. Edit this file; it is the source of truth.
workflow bugfix {
  version "1.0.0"
  description "Write, test, and explicitly accept a focused fix"
  max_cost 5
}

role writer {
  write
  requires "coding.write"
}

agent writer {
  role writer
  objective "Make the smallest safe change requested by the task"
  retry 2
}

check test {
  run "npm test"
  required
}

human accept {
  title "Accept the verified change"
  decisions approve, reject
}

flow {
  writer -> test
  test.pass -> accept
  test.fail -> writer { max 3 }
}
`,
};

function parse(args: string[], cwd: string): Options {
  let json = false;
  let directory = cwd;
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index]!;
    if (arg === '--json') json = true;
    else if (arg === '--dir') {
      const value = args[index + 1];
      if (!value) throw new UsageError('--dir needs a value');
      index += 1;
      directory = resolve(cwd, value);
    } else throw new UsageError(`Unknown option '${arg}'`);
  }
  return { directory: resolve(directory), json };
}

export function initializeProject(directory: string): InitResult {
  const root = resolve(directory, '.roflock');
  const entries = Object.entries(FILES).map(([relativePath, content]) => ({
    relativePath,
    content,
    path: resolve(root, relativePath),
  }));
  const conflicts = entries
    .filter((entry) => existsSync(entry.path) && readFileSync(entry.path, 'utf8') !== entry.content)
    .map((entry) => entry.relativePath);
  if (conflicts.length > 0) return { root, created: [], unchanged: [], conflicts };

  const created: string[] = [];
  const unchanged: string[] = [];
  for (const entry of entries) {
    if (existsSync(entry.path)) {
      unchanged.push(entry.relativePath);
      continue;
    }
    mkdirSync(resolve(entry.path, '..'), { recursive: true });
    writeFileSync(entry.path, entry.content, { flag: 'wx', mode: 0o644 });
    created.push(entry.relativePath);
  }
  return { root, created, unchanged, conflicts: [] };
}

export function runInit(args: string[], io: CliIo, dependencies: { cwd?: string } = {}): number {
  let options: Options;
  try {
    options = parse(args, dependencies.cwd ?? process.cwd());
  } catch (error) {
    return emitUsageError(
      `${(error as Error).message}\nUsage: roflock init [--dir <path>] [--json]`,
      args,
      io,
    );
  }
  try {
    const result = initializeProject(options.directory);
    if (options.json) io.stdout(JSON.stringify(result));
    else if (result.conflicts.length > 0) {
      io.stderr('Roflock did not overwrite existing files:');
      for (const path of result.conflicts) io.stderr(`  .roflock/${path}`);
    } else if (result.created.length === 0) {
      io.stdout(`Roflock is already initialized at ${result.root}.`);
    } else {
      io.stdout(`Initialized Roflock at ${result.root}:`);
      for (const path of result.created) io.stdout(`  .roflock/${path}`);
      if (result.unchanged.length > 0) {
        io.stdout(`Kept ${result.unchanged.length} identical existing file(s).`);
      }
    }
    return result.conflicts.length > 0 ? ExitCode.Blocked : ExitCode.Ok;
  } catch (error) {
    return emitRuntimeError(error, io, options.json, ExitCode.Config);
  }
}
